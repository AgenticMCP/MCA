def _normv(v):
    """One value, normalized for tolerant comparison: numerics (including
    numeric STRINGS — ::text casts and unconstrained-numeric scale make
    '100', 100, '230.0' and 230 all legitimate spellings of the same value)
    compare as floats; everything else as a stripped, lowercased string."""
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return round(float(v), 6)
    s = str(v).strip()
    try:
        return round(float(s), 6)
    except ValueError:
        return s.lower()

def vals_equal(a, b):
    """Tolerant scalar equality — ALWAYS use this instead of == for values
    read back from the database."""
    return _normv(a) == _normv(b)

def rows_equal(rows, expected, ordered=True):
    """Tolerant row comparison. `rows` is a pg_rows result (list[dict]);
    `expected` is a list of dicts (same column aliases) or tuples (values in
    SELECT order). Numeric strings and ints compare equal; identifier case is
    ignored. Returns False (never raises) on None/shape mismatch."""
    if rows is None or expected is None:
        return False
    def _norm_row(r):
        vals = r.values() if isinstance(r, dict) else r
        return tuple(_normv(x) for x in vals)
    try:
        a = [_norm_row(r) for r in rows]
        b = [_norm_row(r) for r in expected]
    except (TypeError, AttributeError):
        return False
    return a == b if ordered else sorted(a) == sorted(b)

