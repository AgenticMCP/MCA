"""Verifier agent: generate + run an execution-based verification script.

The verifier proves the task was carried out correctly. It assembles ONE python
script (``verify.py``) combining three evaluator families, then executes it:

  (1) Format Evaluators  — strict structure checks on each step's trace entry.
      Deterministic.
  (2) Static Evaluators  — value checks on the arguments actually sent.
      Deterministic.
  (3) Dynamic Evaluators — real-time / metamorphic checks that re-query the
      database live through a fresh RESTRICTED (read-only) postgres-mcp
      session (e.g. "the table now exists and holds exactly 3 rows"). This
      section is generated by the LLM, grounded on the tool's Python
      implementation + unit test, then compile-checked and sandboxed so a bad
      snippet can't crash verification.

Between (1) and (3) sits a deterministic live layer, ``sql_write_evaluators``:
every executed CREATE/DROP is re-checked for existence/absence at the exact
object it named, and every INSERT contributes a row-count floor for its table
— no LLM judgment involved. Row CONTENT correctness stays in the dynamic layer
(grounded on the executed SQL, never re-typed from task prose).

This hybrid (deterministic core + LLM-only-for-dynamic) is the key reliability
optimization over fully LLM-generated verification scripts.
"""

